from .base_agent import BaseAgent
import re

class Reviewer(BaseAgent):
    def __init__(self, model_name="Qwen2.5-Coder", num_predict=4096, num_ctx=16384, base_url=None):
        super().__init__(model_name=model_name, num_predict=num_predict, num_ctx=num_ctx, base_url=base_url, temperature=0.1)

    def review(self, task_goal, code, test_cases="", error_msg=""):
        prompt = f"""ROLE: Lead Meta-Logic Auditor & Root-Cause Fault Separator.
TASK: Audit execution failures, isolate whether the root cause stems from algorithmic flaws in CODER or invalid/flawed test logic in TESTER, and output line-level structural feedback.

### [INPUT DATA]:
1. PROBLEM SPECIFICATION (GROUND TRUTH):
{task_goal}

2. CODER SOURCE CODE: 
{code}

3. TEST SCENARIOS (TESTER / METAMORPHIC RELATIONS):
{test_cases}

4. EXECUTION RESULT (SANDBOX TRACEBACK / LOGS): 
{error_msg if error_msg else "Code executed successfully technically."}

---

### [MANDATORY FAULT DISCRIMINATION PROTOCOL]:

Before assigning fault, you MUST independently solve the specification and execute the following 3-Step Verification in your `<thought>`:

#### STEP 1: TESTER VALIDATION (Audit the Test Suite First)
- Inspect the inputs generated by Tester: Do they violate the input constraints defined in `PROBLEM SPECIFICATION`?
- Inspect the expected outputs / Metamorphic Relations (MR) logic: Is Tester's mathematical/logical assertion strictly correct according to `PROBLEM SPECIFICATION`?
- **Decision Boundary**:
  * If Tester passes invalid inputs OR asserts a mathematically incorrect expected output:
    -> **FAULT = TESTER** (Ignore Coder errors caused by invalid test harnesses).

#### STEP 2: CODER VALIDATION (Audit Implementation Second)
- Assuming the Test input is VALID and expected output is CORRECT:
- Trace Coder's state line-by-line using the test input.
- Check for algorithmic flaws (off-by-one, improper base cases, dynamic programming state transitions, incorrect mutation of shared state, unhandled edge cases).
- **Decision Boundary**:
  * If Coder produces incorrect output for a valid test case OR crashes due to poor index/type/value handling:
    -> **FAULT = CODER**.

#### STEP 3: CONSTRAINTS & BOUNDARY ARBITRATION
- If both code and test seem logical, check for **Edge Cases & Ambiguities** in Specification:
  * Null/empty inputs, zero values, floating-point precision, sequence ordering, negative numbers.
  * Who failed to adhere to the spec boundary?
  * If Coder's logic is correct and valid, imidiately flag Tester for misalignment with spec.
    -> **FAULT = TESTER**. 
---

### OUTPUT FORMAT:
<thought>
1. SPEC GROUND TRUTH ANALYSIS:
   - Input Constraints: [Extract explicit & implicit constraints]
   - Expected Behavior: [Formulate expected mathematical/logical mapping]

2. TESTER SANITY CHECK:
   - Evaluated MR/Test: <Test Name>
   - Test Input: <Input values>
   - Tester Expected Output / Relation: <Formula/Value asserted by Tester>
   - Is Tester Assertion Valid against Spec? [YES/NO] -> Reason: [...]

3. CODER EXECUTION TRACE:
   - Coder Actual Output / Crash point: <Value or Line number>
   - Coder Internal State Path: <Trace variable values>
   - Is Coder Logic Valid against Spec? [YES/NO] -> Reason: [...]

4. ADJUDICATION TABLE:
| Test Scenario | Input Valid? | Tester Assertion Correct? | Coder Output Correct? | Responsible Party |
| :--- | :--- | :--- | :--- | :--- |
| <MR_NAME> | <YES/NO> | <VALID/FLAWED> | <CORRECT/INCORRECT/CRASH> | <CODER / TESTER> |

5. FINAL VERDICT RATIONALE:
   [1-2 sentences explaining precisely WHY the chosen target is at fault]
</thought>

AUDIT_SUMMARY:
STATUS: <PASSED | REJECTED>
TARGET: <CODER | TESTER>
FAILED_CASE: <Specific Test/MR Name or "None">
ROOT_CAUSE_LOCATION: <[Function/Method Name] - Line X OR [Tester MR Name] - Line Y>
FAILURE_MECHANISM: <Describe exact discrepancy. e.g., "Tester expected sorted output descending, but Spec mandates ascending." OR "Coder initialized max_val = 0 which fails for all-negative arrays.">
INSTRUCTION: <Provide a deterministic, line-level patch. e.g., "In Coder's script, at Line 14, change `if i > 0:` to `if i >= 0:` to handle the zero-index base case properly.">
"""

        raw_output = self.llm.invoke(prompt)
        return self.post_process_review(raw_output, error_msg)

    def post_process_review(self, text, error_msg):
        if not text: 
            return "STATUS: REJECTED | TARGET: SYSTEM | REASON: Reviewer im lặng."
        
        # 1. Trích xuất Target chính từ câu kết luận cuối cùng của Reviewer
        target_matches = re.findall(r"TARGET:\s*\*?\[?(CODER|TESTER)\]?\*?", text, re.IGNORECASE)
        target = target_matches[-1].upper() if target_matches else "UNKNOWN"

        # 2. Trích xuất REASON
        reason = "Phát hiện lỗi logic thực thi."
        r_match = re.search(r"REASON:?\s*\*?\s*(.*?)(?=\n\*?\s*INSTRUCTION:|\n\*?\s*LOGIC AUDIT|\n\*?\s*STATUS:|$)", text, re.IGNORECASE | re.DOTALL)
        if r_match and r_match.group(1).strip():
            reason = r_match.group(1).strip()
            reason = re.sub(r'</?thought>', '', reason).strip()
            reason = re.sub(r'^\*+|\*+$', '', reason).strip()
        elif error_msg:
            reason = f"Execution error: {error_msg.splitlines()[-1]}"

        # 3. Trích xuất INSTRUCTION
        instruction = "Yêu cầu kiểm tra lại toàn bộ logic."
        i_match = re.search(r"INSTRUCTION:?\s*\*?\s*(.*?)(?=\n\*?\s*LOGIC AUDIT|\n\*?\s*STATUS:|</thought>|$)", text, re.IGNORECASE | re.DOTALL)
        if i_match and i_match.group(1).strip():
            instruction = i_match.group(1).strip()
            instruction = re.sub(r'</?thought>', '', instruction).strip()
            instruction = re.sub(r'^\*+|\*+$', '', instruction).strip()

        # 4. Trích xuất LOGIC AUDIT TABLE
        audit_table = ""
        if "LOGIC AUDIT" in text.upper():
            parts = re.split(r"LOGIC AUDIT.*?\n", text, flags=re.IGNORECASE)
            if len(parts) > 1: 
                table_content = parts[-1].replace("</thought>", "").strip()
                audit_table = "\nLOGIC AUDIT TABLE:\n" + table_content

        if "PASSED" in text.upper() and not error_msg and target == "UNKNOWN": 
            return "PASSED"

        return f"STATUS: REJECTED | TARGET: {target} | REASON: {reason} {audit_table} | INSTRUCTION: {instruction}"